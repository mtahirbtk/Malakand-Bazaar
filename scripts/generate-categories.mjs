// Parses docs/taxonomy.md into src/data/categories.ts.
// Kept as a script so the markdown stays the human-editable source of truth.
import { readFileSync, writeFileSync } from "node:fs";

const md = readFileSync("docs/taxonomy.md", "utf8");

function kebab(s) {
  return s
    .replace(/\(.*?\)/g, " ")      // drop parenthetical qualifiers
    .replace(/&/g, " ")
    .replace(/›/g, " ")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const lines = md.split("\n");
const categories = [];
let current = null;
let buffer = [];

function flush() {
  if (!current) return;
  const raw = buffer
    .join(" ")
    .split("·")
    .map((s) => s.trim())
    .filter(Boolean);

  const seen = new Set();
  current.subcategories = raw.map((name, i) => {
    const isOther = i === raw.length - 1 && /^Other\b/i.test(name);
    let slug = isOther ? `${current.slug}-other` : `${current.slug}-${kebab(name)}`;
    let n = 2;
    while (seen.has(slug)) slug = `${current.slug}-${kebab(name)}-${n++}`;
    seen.add(slug);
    return { slug, nameEn: name, nameUr: name };
  });
  categories.push(current);
  current = null;
  buffer = [];
}

for (const line of lines) {
  const heading = line.match(/^##\s+(\d+)\.\s+(.+?)\s+—\s+(.+?)\s+`(.+?)`\s*$/);
  if (heading) {
    flush();
    const [, sort, nameEn, nameUr, icon] = heading;
    current = {
      slug: kebab(nameEn),
      nameEn,
      nameUr,
      icon,
      sort: Number(sort),
      subcategories: [],
    };
    continue;
  }
  if (current) {
    if (/^(##|---)/.test(line)) { flush(); continue; }
    if (line.trim()) buffer.push(line.trim());
  }
}
flush();

// Integrity checks — fail loudly rather than emit a broken seed.
const allSlugs = categories.flatMap((c) => [c.slug, ...c.subcategories.map((s) => s.slug)]);
const dupes = allSlugs.filter((s, i) => allSlugs.indexOf(s) !== i);
if (dupes.length) throw new Error(`Duplicate slugs: ${[...new Set(dupes)].join(", ")}`);
for (const c of categories) {
  if (!c.subcategories.length) throw new Error(`${c.slug} has no subcategories`);
  if (!c.subcategories.at(-1).slug.endsWith("-other"))
    throw new Error(`${c.slug} does not end with an Other subcategory (got "${c.subcategories.at(-1).nameEn}")`);
}

const header = `// GENERATED by scripts/generate-categories.mjs from docs/taxonomy.md.
// Edit the markdown and re-run \`node scripts/generate-categories.mjs\`.
import type { Category } from "@/types";
import type { SelectOption } from "@/components/ui/select";

export const CATEGORIES: Category[] = ${JSON.stringify(categories, null, 2)};

export const CATEGORY_OPTIONS: SelectOption[] = CATEGORIES.map((c) => ({
  value: c.slug,
  label: c.nameEn,
  icon: c.icon,
}));

export function allSubcategoryOptions(): SelectOption[] {
  return CATEGORIES.flatMap((c) =>
    c.subcategories.map((s) => ({
      value: s.slug,
      label: \`\${c.nameEn} › \${s.nameEn}\`,
      icon: c.icon,
    }))
  );
}

export function findCategory(slug: string): Category | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}
`;

writeFileSync("src/data/categories.ts", header);
console.log(
  `categories: ${categories.length}, subcategories: ${categories.reduce((n, c) => n + c.subcategories.length, 0)}`
);
