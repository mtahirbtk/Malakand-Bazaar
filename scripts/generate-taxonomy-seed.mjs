// Generates supabase/seed/001_taxonomy.sql from the two authored sources:
//   docs/taxonomy.md      → categories + subcategories (26 → 444)
//   src/data/tehsils.json → tehsils + localities (3 → 18)
//
// This is reference data, not sample content — it is the district's real
// geography and the marketplace's real category tree. Re-run after editing
// either source, then `npm run db:migrate -- --seed`.
//
//   node scripts/generate-taxonomy-seed.mjs

import { readFileSync, writeFileSync } from "node:fs";

function kebab(s) {
  return s
    .replace(/\(.*?\)/g, " ")
    .replace(/&/g, " ")
    .replace(/›/g, " ")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Parses docs/taxonomy.md. Same grammar as scripts/generate-categories.mjs. */
function parseTaxonomy(md) {
  const categories = [];
  let current = null;
  let buffer = [];

  function flush() {
    if (!current) return;
    const raw = buffer.join(" ").split("·").map((s) => s.trim()).filter(Boolean);
    const seen = new Set();
    current.subcategories = raw.map((name, i) => {
      const isOther = i === raw.length - 1 && /^Other\b/i.test(name);
      let slug = isOther ? `${current.slug}-other` : `${current.slug}-${kebab(name)}`;
      let n = 2;
      while (seen.has(slug)) slug = `${current.slug}-${kebab(name)}-${n++}`;
      seen.add(slug);
      return { slug, nameEn: name, nameUr: name };
    });
    categories.push(current);
    current = null;
    buffer = [];
  }

  for (const line of md.split("\n")) {
    const heading = line.match(/^##\s+(\d+)\.\s+(.+?)\s+—\s+(.+?)\s+`(.+?)`\s*$/);
    if (heading) {
      flush();
      const [, sort, nameEn, nameUr, icon] = heading;
      current = { slug: kebab(nameEn), nameEn, nameUr, icon, sort: Number(sort), subcategories: [] };
      continue;
    }
    if (current) {
      if (/^(##|---)/.test(line)) { flush(); continue; }
      if (line.trim()) buffer.push(line.trim());
    }
  }
  flush();
  return categories;
}

const categories = parseTaxonomy(readFileSync("docs/taxonomy.md", "utf8"));
const tehsils = JSON.parse(readFileSync("src/data/tehsils.json", "utf8"));

// Fail loudly rather than emit a broken seed.
const allSlugs = categories.flatMap((c) => [c.slug, ...c.subcategories.map((s) => s.slug)]);
const dupes = [...new Set(allSlugs.filter((s, i) => allSlugs.indexOf(s) !== i))];
if (dupes.length) throw new Error(`Duplicate category slugs: ${dupes.join(", ")}`);
for (const c of categories) {
  if (!c.subcategories.length) throw new Error(`${c.slug} has no subcategories`);
}
const localitySlugs = tehsils.flatMap((t) => t.localities.map((l) => l.slug));
const localityDupes = [...new Set(localitySlugs.filter((s, i) => localitySlugs.indexOf(s) !== i))];
if (localityDupes.length) throw new Error(`Duplicate locality slugs: ${localityDupes.join(", ")}`);

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const out = [];
out.push("-- GENERATED by scripts/generate-taxonomy-seed.mjs — do not edit by hand.");
out.push("-- Sources: docs/taxonomy.md, src/data/tehsils.json");
out.push("--");
out.push("-- Idempotent: re-running updates names/icons/sort and leaves ids alone.");
out.push("-- Rows removed from the source are deactivated, never deleted, because a");
out.push("-- listing may still reference them.");
out.push("");

out.push("-- Tehsils ------------------------------------------------------------------");
out.push("insert into public.tehsils (slug, name_en, name_ur, revenue_tehsil, sort) values");
out.push(
  tehsils
    .map((t, i) => `  (${q(t.slug)}, ${q(t.nameEn)}, ${q(t.nameUr)}, ${q(t.revenueTehsil)}, ${i + 1})`)
    .join(",\n") + "\non conflict (slug) do update set"
);
out.push("  name_en = excluded.name_en, name_ur = excluded.name_ur,");
out.push("  revenue_tehsil = excluded.revenue_tehsil, sort = excluded.sort, is_active = true;");
out.push("");

out.push("-- Localities ---------------------------------------------------------------");
out.push("insert into public.localities (slug, tehsil_slug, name_en, name_ur, sort) values");
const localityRows = [];
for (const t of tehsils) {
  t.localities.forEach((l, i) => {
    localityRows.push(`  (${q(l.slug)}, ${q(t.slug)}, ${q(l.nameEn)}, ${q(l.nameUr)}, ${i + 1})`);
  });
}
out.push(localityRows.join(",\n") + "\non conflict (slug) do update set");
out.push("  tehsil_slug = excluded.tehsil_slug, name_en = excluded.name_en,");
out.push("  name_ur = excluded.name_ur, sort = excluded.sort, is_active = true;");
out.push("");

out.push("-- Categories (top level) ---------------------------------------------------");
out.push("insert into public.categories (slug, parent_slug, name_en, name_ur, icon, sort) values");
out.push(
  categories
    .map((c) => `  (${q(c.slug)}, null, ${q(c.nameEn)}, ${q(c.nameUr)}, ${q(c.icon)}, ${c.sort})`)
    .join(",\n") + "\non conflict (slug) do update set"
);
out.push("  name_en = excluded.name_en, name_ur = excluded.name_ur,");
out.push("  icon = excluded.icon, sort = excluded.sort, is_active = true;");
out.push("");

out.push("-- Subcategories ------------------------------------------------------------");
out.push("insert into public.categories (slug, parent_slug, name_en, name_ur, icon, sort) values");
const subRows = [];
for (const c of categories) {
  c.subcategories.forEach((s, i) => {
    subRows.push(`  (${q(s.slug)}, ${q(c.slug)}, ${q(s.nameEn)}, ${q(s.nameUr)}, null, ${i + 1})`);
  });
}
out.push(subRows.join(",\n") + "\non conflict (slug) do update set");
out.push("  parent_slug = excluded.parent_slug, name_en = excluded.name_en,");
out.push("  name_ur = excluded.name_ur, sort = excluded.sort, is_active = true;");
out.push("");

out.push("-- Deactivate anything no longer present in the source files.");
out.push("update public.categories set is_active = false");
out.push(` where slug not in (${allSlugs.map(q).join(", ")});`);
out.push("");

writeFileSync("supabase/seed/001_taxonomy.sql", out.join("\n"));

console.log(
  `seed written: ${tehsils.length} tehsils, ${localityRows.length} localities, ` +
    `${categories.length} categories, ${subRows.length} subcategories`
);
